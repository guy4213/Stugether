// scripts/catalog/templates.mjs
// Interim catalog for institutions we have not imported yet: every department
// gets the courses and syllabus of the same degree at HIT (the only fully
// imported institution), so students everywhere can study by topic now.
//
//   node scripts/catalog/templates.mjs YYYYMMDDNNNNNN_degree_templates.sql
//
// The generated migration runs after the HIT catalog migration and copies
// HIT's rows inside the database. Copies get no course code (codes are
// HIT's), and their topics are labelled "equivalent_course / draft" with a
// reference to the HIT course. Replace a department with its institution's
// real catalog when one is imported (scripts/catalog/README).

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const HIT = "H.IT";

// [institution, department] ← HIT degree.
export const TEMPLATES = [
  ["מכללת אפקה", "מדעי המחשב", "מדעי המחשב"],
  ["מכללת אפקה", "הנדסת תוכנה", "מדעי המחשב"],
  ["מכללת אפקה", "הנדסת מערכות מידע", "מדעי המחשב"],
  ["מכללת אפקה", "מדעי הנתונים ובינה מלאכותית", "מדעי המחשב"],
  ["מכללת אפקה", "הנדסת חשמל", "הנדסת חשמל ואלקטרוניקה"],
  ["מכללת אפקה", "הנדסת תעשייה וניהול", "הנדסת תעשייה וניהול טכנולוגיה"],
  ["מכללת אפקה", "הנדסה רפואית", "טכנולוגיות רפואיות דיגיטליות"],
  ["האוניברסיטה העברית", "מדעי המחשב וההנדסה", "מדעי המחשב"],
  ["האוניברסיטה העברית", "מתמטיקה", "מתמטיקה שימושית"],
  ["אוניברסיטת בן־גוריון", "מדעי המחשב", "מדעי המחשב"],
  ["אוניברסיטת בן־גוריון", "הנדסת תוכנה ומערכות מידע", "מדעי המחשב"],
  ["אוניברסיטת בן־גוריון", "מתמטיקה", "מתמטיקה שימושית"],
  ["אוניברסיטת בן־גוריון", "הנדסת חשמל ומחשבים", "הנדסת חשמל ואלקטרוניקה"],
  ["אוניברסיטת בן־גוריון", "הנדסת תעשייה וניהול", "הנדסת תעשייה וניהול טכנולוגיה"],
];

const q = (v) => `'${String(v).replaceAll("'", "''")}'`;

async function main() {
  const name = process.argv[2];
  if (!name || !/^\d{14}_[a-z0-9_]+\.sql$/.test(name)) {
    throw new Error("usage: node scripts/catalog/templates.mjs YYYYMMDDNNNNNN_name.sql");
  }
  // The handbook lists each degree's courses, including service courses that
  // live in another HIT department (e.g. probability for CS).
  const hit = JSON.parse(await readFile(path.join(ROOT, "supabase/catalog/hit.json"), "utf8"));
  const codesByDegree = new Map(hit.departments.map((d) => [d.name, d.courses.map((c) => c.code)]));

  const rows = [];
  for (const [institution, department, degree] of TEMPLATES) {
    const codes = codesByDegree.get(degree);
    if (!codes) throw new Error(`unknown HIT degree: ${degree}`);
    for (const code of codes) rows.push(`  (${q(institution)}, ${q(department)}, ${q(code)})`);
  }

  const sql = `-- =============================================================================
-- ${name}
-- GENERATED by scripts/catalog/templates.mjs. Interim catalog: each listed
-- department of another institution gets the courses + syllabus of the same
-- degree at H.IT (copied from the H.IT rows of 20261010000002). Copies have no
-- code; their topics are 'equivalent_course' / 'draft' and reference the HIT
-- course. Departments with no HIT counterpart keep their starter courses.
-- =============================================================================

CREATE TEMP TABLE _tpl (institution text, department text, hit_code text);
INSERT INTO _tpl VALUES
${rows.join(",\n")};

-- Target department + the HIT course each copy comes from.
CREATE TEMP TABLE _tpl_src AS
SELECT d.institution_id, d.id AS department_id,
       src.id, src.code, src.name, src.year_level, src.semester, src.credits, src.description
  FROM _tpl t
  JOIN public.institutions ti ON ti.name = t.institution
  JOIN public.departments d ON d.institution_id = ti.id AND d.name = t.department
  JOIN public.institutions hi ON hi.name = ${q(HIT)}
  JOIN public.courses src ON src.institution_id = hi.id AND src.code = t.hit_code AND src.is_active;

-- 1. The starter courses of these departments are replaced.
UPDATE public.courses c
   SET is_active = false
 WHERE c.code IS NULL
   AND c.department_id IN (SELECT DISTINCT department_id FROM _tpl_src)
   AND NOT EXISTS (SELECT 1 FROM public.course_topics ct WHERE ct.course_id = c.id);

-- 2. Courses (one per department + name).
INSERT INTO public.courses
  (institution_id, department_id, code, name, year_level, semester, credits, description, source_url, is_active)
SELECT DISTINCT ON (s.department_id, s.name)
       s.institution_id, s.department_id, NULL, s.name, s.year_level, s.semester, s.credits, s.description, NULL, true
  FROM _tpl_src s
 WHERE NOT EXISTS (
         SELECT 1 FROM public.courses c
          WHERE c.department_id = s.department_id AND c.name = s.name AND c.code IS NULL AND c.is_active)
 ORDER BY s.department_id, s.name, s.code;

CREATE TEMP TABLE _tpl_map AS
SELECT DISTINCT ON (c.id) c.id AS course_id, s.id AS src_id, s.code AS src_code, s.name AS src_name
  FROM _tpl_src s
  JOIN public.courses c
    ON c.department_id = s.department_id AND c.name = s.name AND c.code IS NULL AND c.is_active
 WHERE NOT EXISTS (SELECT 1 FROM public.course_topics ct WHERE ct.course_id = c.id)
 ORDER BY c.id, s.code;

-- 3. Topics, then subtopics under the copied parents (matched by position).
INSERT INTO public.course_topics (course_id, position, title, description, source, status, source_ref, source_url)
SELECT m.course_id, t.position, t.title, t.description, 'equivalent_course', 'draft',
       pg_catalog.left('H.IT ' || m.src_code || ' ' || m.src_name, 200), t.source_url
  FROM _tpl_map m
  JOIN public.course_topics t ON t.course_id = m.src_id AND t.parent_id IS NULL AND t.is_active;

INSERT INTO public.course_topics (course_id, parent_id, position, title, description, source, status, source_ref, source_url)
SELECT m.course_id, np.id, st.position, st.title, st.description, 'equivalent_course', 'draft', np.source_ref, st.source_url
  FROM _tpl_map m
  JOIN public.course_topics sp ON sp.course_id = m.src_id AND sp.parent_id IS NULL
  JOIN public.course_topics st ON st.parent_id = sp.id AND st.is_active
  JOIN public.course_topics np ON np.course_id = m.course_id AND np.parent_id IS NULL AND np.position = sp.position;

DROP TABLE _tpl, _tpl_src, _tpl_map;
`;
  const out = path.join(ROOT, "supabase/migrations", name);
  await writeFile(out, sql);
  console.error(
    `→ ${path.relative(ROOT, out)}: ${rows.length} course placements in ${TEMPLATES.length} departments`,
  );
}

if (process.argv[1]?.endsWith("templates.mjs")) await main();
