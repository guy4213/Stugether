// scripts/catalog/to-sql.mjs
// Generates the HIT catalog migration from supabase/catalog/hit-courses.json.
//
//   node scripts/catalog/to-sql.mjs <migration file name>
//   e.g. node scripts/catalog/to-sql.mjs 20261010000002_hit_catalog.sql
//
// The migration is idempotent and keyed by HIT course code:
//   - upserts every course (name, department, year, semester, credits, ...);
//   - deactivates HIT's code-less starter courses from 20260930000003
//     (deactivate, not delete: enrollments/rooms may point at them);
//   - inserts topics + subtopics for courses that have none yet, so topics an
//     admin has since edited are never overwritten by a re-run.
// Write a NEW migration for each re-import; never edit an applied one.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const INPUT = path.join(ROOT, "supabase/catalog/hit-courses.json");
const INSTITUTION = "H.IT";

// A course code shared by several programs (e.g. 20021 probability) is one
// course; it lives in the department that owns the code range.
const HOME_BY_PREFIX = [
  [/^2[01]/, "מתמטיקה שימושית"],
  [/^6/, "מדעי המחשב"],
  [/^5/, "הנדסת חשמל ואלקטרוניקה"],
  [/^7/, "הנדסת תעשייה וניהול טכנולוגיה"],
  [/^1/, "טכנולוגיות למידה"],
  [/^4/, "טכנולוגיות רפואיות דיגיטליות"],
];

const SOURCE = {
  hit_current: { source: "official_description", status: "verified", label: "HIT" },
  hit_archive: { source: "official_syllabus", status: "verified", label: "HIT" },
  // Same institution, older syllabus matched by name: likely but not certain.
  hit_archive_name: { source: "official_syllabus", status: "draft", label: "HIT" },
  technion: { source: "equivalent_course", status: "draft", label: "Technion" },
  braude: { source: "equivalent_course", status: "draft", label: "בראודה" },
  openu: { source: "equivalent_course", status: "draft", label: "האוניברסיטה הפתוחה" },
};

const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replaceAll("'", "''")}'`);
const num = (v) => (v === null || v === undefined ? "NULL" : String(v));
const clip = (s, n) => (s && s.length > n ? s.slice(0, n - 1).trimEnd() + "…" : s);

function pickCourses(catalog) {
  const byCode = new Map();
  for (const dept of catalog.departments) {
    for (const course of dept.courses) {
      const entry = byCode.get(course.code) ?? { course, departments: [] };
      entry.departments.push(dept.name);
      // Keep the copy with topics (and the earliest placement) when duplicated.
      if (!entry.course.topics_source && course.topics_source) entry.course = course;
      byCode.set(course.code, entry);
    }
  }
  return [...byCode.values()].map(({ course, departments }) => {
    const home = HOME_BY_PREFIX.find(
      ([re, name]) => re.test(course.code) && departments.includes(name),
    );
    return { ...course, department: home?.[1] ?? departments[0] };
  });
}

function main() {
  return readFile(INPUT, "utf8").then(async (raw) => {
    const name = process.argv[2];
    if (!name || !/^\d{14}_[a-z0-9_]+\.sql$/.test(name)) {
      throw new Error("usage: node scripts/catalog/to-sql.mjs YYYYMMDDNNNNNN_name.sql");
    }
    const catalog = JSON.parse(raw);
    const courses = pickCourses(catalog);

    const courseRows = courses.map(
      (c) =>
        `  (${q(c.code)}, ${q(c.department)}, ${q(clip(c.name, 200))}, ${num(c.year_level)}, ${q(c.semester)}, ${num(c.credits)}, ${q(clip(c.description, 4000))}, ${q(c.source_url)})`,
    );

    const topicRows = [];
    const subRows = [];
    for (const c of courses) {
      if (!c.topics_source || c.topics.length === 0) continue;
      const src = SOURCE[c.topics_source.kind];
      const ref = clip(`${src.label} ${c.topics_source.ref ?? ""}`.trim(), 200);
      c.topics.forEach((t, i) => {
        topicRows.push(
          `  (${q(c.code)}, ${i + 1}, ${q(clip(t.title, 120))}, ${q(src.source)}, ${q(src.status)}, ${q(ref)}, ${q(c.topics_source.url)})`,
        );
        t.subtopics.forEach((s, j) => {
          subRows.push(`  (${q(c.code)}, ${i + 1}, ${j + 1}, ${q(clip(s, 120))})`);
        });
      });
    }

    const sql = `-- =============================================================================
-- ${name}
-- GENERATED by scripts/catalog/to-sql.mjs from supabase/catalog/hit-courses.json
-- (${catalog.enriched_at}). Do not edit by hand — re-run the pipeline and write
-- a new migration instead (see supabase/catalog/README.md).
--
-- HIT (H.IT) catalog: ${courses.length} courses from the faculty handbooks, with
-- topics for ${courses.filter((c) => c.topics_source).length} of them. Topic provenance is stored per row
-- (course_topics.source / status / source_ref / source_url).
-- =============================================================================

-- 1. Courses -------------------------------------------------------------------
INSERT INTO public.courses
  (institution_id, department_id, code, name, year_level, semester, credits, description, source_url, is_active)
SELECT i.id, d.id, v.code, v.name, v.year_level, v.semester, v.credits, v.description, v.source_url, true
FROM (VALUES
${courseRows.join(",\n")}
) AS v (code, department, name, year_level, semester, credits, description, source_url)
JOIN public.institutions i ON i.name = ${q(INSTITUTION)}
LEFT JOIN public.departments d ON d.institution_id = i.id AND d.name = v.department
ON CONFLICT (institution_id, code) WHERE code IS NOT NULL DO UPDATE
  SET department_id = EXCLUDED.department_id,
      name          = EXCLUDED.name,
      year_level    = EXCLUDED.year_level,
      semester      = EXCLUDED.semester,
      credits       = EXCLUDED.credits,
      description   = COALESCE(EXCLUDED.description, public.courses.description),
      source_url    = EXCLUDED.source_url,
      is_active     = true;

-- 2. HIT's code-less starter courses are replaced by the real catalog ---------
UPDATE public.courses c
   SET is_active = false
  FROM public.institutions i
 WHERE c.institution_id = i.id
   AND i.name = ${q(INSTITUTION)}
   AND c.code IS NULL;

-- 3. Topics (only for courses that have none yet) -----------------------------
CREATE TEMP TABLE _hit_topics (code text, position smallint, title text, source text, status text, source_ref text, source_url text);
INSERT INTO _hit_topics VALUES
${topicRows.join(",\n")};

CREATE TEMP TABLE _hit_subtopics (code text, parent_position smallint, position smallint, title text);
${subRows.length > 0 ? `INSERT INTO _hit_subtopics VALUES\n${subRows.join(",\n")};` : "-- (no subtopics)"}

CREATE TEMP TABLE _hit_fresh AS
SELECT c.id AS course_id, c.code
  FROM public.courses c
  JOIN public.institutions i ON i.id = c.institution_id AND i.name = ${q(INSTITUTION)}
 WHERE c.code IN (SELECT DISTINCT code FROM _hit_topics)
   AND NOT EXISTS (SELECT 1 FROM public.course_topics ct WHERE ct.course_id = c.id);

INSERT INTO public.course_topics (course_id, position, title, source, status, source_ref, source_url)
SELECT f.course_id, t.position, t.title, t.source, t.status, t.source_ref, t.source_url
  FROM _hit_topics t
  JOIN _hit_fresh f ON f.code = t.code;

INSERT INTO public.course_topics (course_id, parent_id, position, title, source, status, source_ref, source_url)
SELECT f.course_id, p.id, s.position, s.title, p.source, p.status, p.source_ref, p.source_url
  FROM _hit_subtopics s
  JOIN _hit_fresh f ON f.code = s.code
  JOIN public.course_topics p
    ON p.course_id = f.course_id AND p.parent_id IS NULL AND p.position = s.parent_position;

DROP TABLE _hit_topics, _hit_subtopics, _hit_fresh;
`;
    const out = path.join(ROOT, "supabase/migrations", name);
    await writeFile(out, sql);
    console.error(
      `→ ${path.relative(ROOT, out)}: ${courseRows.length} courses, ${topicRows.length} topics, ${subRows.length} subtopics`,
    );
  });
}

await main();
